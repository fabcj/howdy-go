package pyfmt

import "testing"

// Expected values printed by python3 3.14 and numpy 2
var floatCases = []struct {
	in   float64
	want string
}{
	{0.0, "0.0"},
	{0.5, "0.5"},
	{1.0, "1.0"},
	{0.1, "0.1"},
	{-0.0123, "-0.0123"},
	{1e-05, "1e-05"},
	{2.5e-07, "2.5e-07"},
	{1e+16, "1e+16"},
	{1.2345678901234568e+17, "1.2345678901234568e+17"},
	{123456789012345.6, "123456789012345.6"},
	{1234567.0, "1234567.0"},
	{9999999999999998.0, "9999999999999998.0"},
	{0.0001, "0.0001"},
	{0.00011, "0.00011"},
	{5e-324, "5e-324"},
	{1.7976931348623157e+308, "1.7976931348623157e+308"},
	{60.0, "60.0"},
	{3.5, "3.5"},
	{100.0, "100.0"},
	{0.30000000000000004, "0.30000000000000004"},
	{0.10000000149011612, "0.10000000149011612"},
	{-3e-05, "-3e-05"},
	{-0.7312715117751976, "-0.7312715117751976"},
	{0.6948674738744653, "0.6948674738744653"},
	{-0.009129825816118098, "-0.009129825816118098"},
}

var roundCases = []struct {
	in   float64
	n    int
	want float64
}{
	{0.534, 2, 0.53},
	{8.0, 2, 8.0},
	{0.125, 2, 0.12},
	{0.375, 2, 0.38},
	{2.675, 2, 2.67},
	{22.641509433962263, 2, 22.64},
	{31.04999, 1, 31.0},
	{3.05, 1, 3.0},
	{1.0000000001, 2, 1.0},
}

var f32Cases = []struct {
	in   float32
	want string
}{
	{55.113887786865234, "[55.113888]"},
	{60.000003814697266, "[60.000004]"},
	{0.0, "[0.]"},
	{60.0, "[60.]"},
	{87.5, "[87.5]"},
	{0.0004340277810115367, "[0.00043403]"},
	{12.34567928314209, "[12.345679]"},
	{99.99999237060547, "[99.99999]"},
	{100.0, "[100.]"},
	{1.4999999621068127e-05, "[1.5e-05]"},
	{33.33333206176758, "[33.333332]"},
}

func TestFloat(t *testing.T) {
	for _, c := range floatCases {
		if got := Float(c.in); got != c.want {
			t.Errorf("Float(%v) = %q, want %q", c.in, got, c.want)
		}
	}
	negZero := 0.0
	negZero = -negZero
	if got := Float(negZero); got != "-0.0" {
		t.Errorf("Float(-0.0) = %q", got)
	}
}

func TestRound(t *testing.T) {
	for _, c := range roundCases {
		if got := Round(c.in, c.n); got != c.want {
			t.Errorf("Round(%v, %d) = %v, want %v", c.in, c.n, got, c.want)
		}
	}
}

func TestFloat32Array(t *testing.T) {
	for _, c := range f32Cases {
		if got := Float32Array(c.in); got != c.want {
			t.Errorf("Float32Array(%v) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestFloat32(t *testing.T) {
	for _, c := range []struct {
		in   float32
		want string
	}{
		{55.113887786865234, "55.113888"},
		{60.000003814697266, "60.000004"},
		{0.0, "0.0"},
		{60.0, "60.0"},
		{87.5, "87.5"},
		{0.0004340277810115367, "0.00043402778"},
		{12.34567928314209, "12.345679"},
		{99.99999237060547, "99.99999"},
		{100.0, "100.0"},
		{1.4999999621068127e-05, "1.5e-05"},
		{33.33333206176758, "33.333332"},
		{1.0000000272564224e+16, "1e+16"},
		{2.9999999242136255e-05, "3e-05"},
		{123456792.0, "1.2345679e+08"},
	} {
		if got := Float32(c.in); got != c.want {
			t.Errorf("Float32(%v) = %q, want %q", c.in, got, c.want)
		}
	}
}
